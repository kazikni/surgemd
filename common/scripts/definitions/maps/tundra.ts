export function create_hunt_house(id:string,settings:{
        walls_tint?:number
        doors_tint?:number
        b?:DeepPartial<BuildingDef>
        content?:BuildingObstacles[]
}={}){
    const walls_tint=settings.walls_tint??1
    const doors_tint=settings.doors_tint??walls_tint
    return mergeDeep({
        idString:id,
        no_collisions:true,
        no_bullet_collision:true,
        assets:{
            particles:{
                particle:"plank_particle",
                tint:0x656877,
            }
        },
        content:{
            obstacles:[
                {
                    def:"wood_door",
                    position:v2(1.76,0.739998),
                    rotation:3,
                    id:1,
                    variation:doors_tint
                },
                {
                    def:"stone_wall_4x1",
                    position:v2(1.76,-1.21),
                    rotation:1,
                    id:10,
                    variation:walls_tint
                },
                {
                    def:"stone_wall_4x1",
                    position:v2(1.76,1.21),
                    rotation:1,
                    connections:[1],
                    id:11,
                    variation:walls_tint
                },

                {
                    def:"stone_wall_14x1",
                    position:v2(0,-1.57),
                    rotation:0,
                    id:12,
                    variation:walls_tint
                },
                {
                    def:"stone_wall_14x1",
                    position:v2(0,1.57),
                    rotation:0,
                    id:13,
                    variation:walls_tint
                },

                {
                    def:"wood_door",
                    position:v2(-1.76,0.739998),
                    rotation:3,
                    id:2,
                    variation:doors_tint
                },
                {
                    def:"stone_wall_4x1",
                    position:v2(-1.76,-1.21),
                    rotation:1,
                    id:14,
                    variation:walls_tint
                },
                {
                    def:"stone_wall_4x1",
                    position:v2(-1.76,1.21),
                    rotation:1,
                    connections:[2],
                    id:15,
                    variation:walls_tint
                },
                ...(settings.content??[])
            ],
            ceiling:[ 
                {
                    frame:{
                        image:"hunt_house_ceiling_1",
                        position:v2.zero(),
                        rotation:0
                    },
                    connections:[10,11,12,13,14,15],
                    destroy:{
                        frame:"hunt_house_ceiling_break",
                        sound:"ceiling_break_1",
                        count:3,
                        particles:{
                            count:30
                        }
                    },
                    hitbox:new RectHitbox2D(v2(-1.75,-1.55),v2(1.75,1.55)),
                }
            ],
            floor_image:[
                {
                    image:"hunt_house_floor",
                    position:v2(0,0),
                }
            ],
        },
        hitbox:RectHitbox2D.centered(v2(0,0),v2(3.5,3.1)),
    },settings.b??{})
}
